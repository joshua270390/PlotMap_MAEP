-- Run once in the Supabase SQL Editor for the MAEP project.
create table if not exists public.employees (
  id bigint generated by default as identity primary key,
  username text not null unique,
  email text not null unique,
  password_salt text not null,
  password_hash text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.employees enable row level security;
-- Employee records are accessed only by Netlify Functions using the service-role key.
-- Do not create public anon/authenticated policies for this table.
