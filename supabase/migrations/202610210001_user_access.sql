-- Run this migration in the Supabase SQL Editor for the PlotMap_MAEP project.
-- PINs are stored as salted scrypt hashes, never as plaintext.
create table if not exists public.user_access (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 120),
  email text not null unique,
  pin_hash text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'revoked')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.user_access enable row level security;

-- No anon/authenticated table policies are intentionally created.
-- Reads and writes must go through the Netlify function using the server-only
-- Supabase service role key. Never expose that key to the browser.
